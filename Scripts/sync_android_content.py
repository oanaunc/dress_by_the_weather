#!/usr/bin/env python3
"""Export canonical iOS editorial content into the native Android source tree."""
import re, json, shutil
from pathlib import Path
r = Path(__file__).resolve().parent.parent
assets = r/'Android/app/src/main/assets'; assets.mkdir(parents=True, exist_ok=True)
s = (r/'App/EditorialLibraryView.swift').read_text()
guides = []
for line in s.splitlines():
 if '.init(id:' not in line: continue
 match = re.search(r'\.init\(id: "(.*?)", title: "(.*?)", subtitle: "(.*?)", collections: \[(.*?)\], notes: \[(.*)\]\)', line)
 if match:
  identifier,title,subtitle,collections,notes=match.groups()
  guides.append(dict(id=identifier,title=title,subtitle=subtitle,collections=re.findall(r'"(.*?)"',collections),notes=[dict(title=a,body=b) for a,b in re.findall(r'\("(.*?)", "(.*?)"\)',notes)]))
assert len(guides)==8
(assets/'guides.json').write_text(json.dumps(guides,ensure_ascii=False,indent=2)+'\n')
s = (r/'Core/Sources/WeatherStyle/OutfitEngine.swift').read_text()
blocks = re.findall(r'case ([^:\n]+):\n\s+items = \[(.*?)\]\n',s)
base = []
for name,block in blocks:
 if not name.startswith('.'): continue
 items=[]
 for expr in re.findall(r'\.init\((.*?)\)',block):
  fields=re.split(r', (?=(?:[^\"]*\"[^\"]*\")*[^\"]*$)',expr)
  assert len(fields)==4,(name,fields)
  variants=[]
  for formal in [False,True]:
   row=[]
   for field in fields:
    strings=re.findall(r'"(.*?)"',field)
    row.append(strings[0 if formal or len(strings)==1 else 1])
   variants.append(dict(zip(['category','name','fabric','icon'],row)))
  items.append(variants)
 base.append([[i[0] for i in items],[i[1] for i in items]])
assert len(base)==8,len(base)
# Last switch block covers summer, hot and extreme heat.
base += [base[-1],base[-1]]
(assets/'base-outfits.json').write_text(json.dumps(base,ensure_ascii=False,indent=2)+'\n')
# Generate Kotlin constants from these strings, without an Android dependency.
def k(s):return json.dumps(s,ensure_ascii=False)
rows=[]
for band in base:
 rows.append('listOf('+','.join('listOf('+','.join('Item('+','.join(k(i[v]) for v in ['category','name','fabric','icon'])+')' for i in variant)+')' for variant in band)+')')
(r/'Android/app/src/main/java/com/oanarinaldi/dressbytheweather/BaseOutfits.kt').write_text('// Generated by Scripts/sync_android_content.py from the Swift outfit engine.\npackage com.oanarinaldi.dressbytheweather\ninternal val baseOutfits = listOf(\n'+',\n'.join(rows)+'\n)\n')
print('Exported eight original guides and ten exact outfit blueprints. Art and lookbook are synced by Gradle from the iOS sources.')
